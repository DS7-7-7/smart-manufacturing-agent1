"""
tools.py

에이전트가 사용할 도구를 정의한다.

실습에서는 실제 MES/GraphRAG 시스템 대신 시뮬레이션 함수를 사용한다.
실전 배포 시에는 각 함수의 내부를 실제 API 호출로 교체하면 된다.

도구 3종:
  - query_mes_data      : MES 시스템에서 생산·불량 데이터 조회
  - graphrag_search     : 제조 지식 그래프에서 설비·부품·이력 관계 검색
  - check_defect_type   : 특정 라인의 불량 유형 분포 조회
"""

from langchain.tools import tool


# ============================================================
# 도구 1: MES 데이터 조회
# ============================================================
@tool
def query_mes_data(query: str) -> str:
    """MES 시스템에서 생산·불량 데이터를 조회한다.

    질의 예시:
      - "이번 달 라인별 불량률"
      - "지난 3개월 A라인 생산량"
      - "이번 주 야간조 생산 실적"
    """
    # 실전에서는 아래 부분을 실제 MES REST API 호출로 교체
    # 예: response = requests.get(f"{MES_API_URL}/defect-rates", params={...})

    if "라인별 불량률" in query:
        return (
            "이번 달 라인별 불량률 (지난달 대비):\n"
            "- 라인 A: 2.1% → 2.3% (변화 미미)\n"
            "- 라인 B: 1.8% → 5.2% (급증)\n"
            "- 라인 C: 2.0% → 2.1% (변화 미미)"
        )

    if "생산량" in query and "라인" in query:
        return (
            "지난 3개월 라인별 생산량 (단위: 만개):\n"
            "- 라인 A: 12.4 / 12.6 / 12.3\n"
            "- 라인 B: 15.8 / 15.2 / 14.1 (감소 추세)\n"
            "- 라인 C: 10.2 / 10.4 / 10.5"
        )

    return "조회 결과 없음. 질의를 더 구체적으로 표현해주세요."


# ============================================================
# 도구 2: GraphRAG 검색
# ============================================================
@tool
def graphrag_search(query: str) -> str:
    """제조 지식 그래프에서 설비·부품·이력 관계를 검색한다.

    질의 예시:
      - "라인 B 연결 설비"
      - "다이 D-2201 과거 불량 사례"
      - "냉각기 CL-105 정비 이력"
    """
    # 실전에서는 아래 부분을 GraphRAG 파이프라인 호출로 교체
    # 예: Neo4j Cypher 쿼리 → LLM 요약 반환

    if "라인 B" in query and ("설비" in query or "정비" in query):
        return (
            "라인 B 구성 설비:\n"
            "- 압출기 EX-201 (다이 D-2201 장착)\n"
            "- 냉각기 CL-105\n"
            "- 검사기 IN-303\n"
            "\n최근 정비 이력:\n"
            "- 2주 전: EX-201 다이 교체 "
            "(부품: D-2201, 공급업체: X사, 신규 계약)\n"
            "- 5주 전: CL-105 정기 점검 (이상 없음)"
        )

    if "다이 D-2201" in query and "사례" in query:
        return (
            "과거 유사 사례 (2024-03):\n"
            "- 동일 부품(D-2201) 교체 후 불량률 2주 만에 3배 증가\n"
            "- 원인: 다이 표면 조도 규격 미달 (Ra 0.8 초과)\n"
            "- 조치: 공급업체 변경 후 정상화\n"
            "- 관련 문서: 품질 이슈 보고서 QIR-2024-0312"
        )

    if "CL-105" in query:
        return (
            "냉각기 CL-105 정보:\n"
            "- 설치: 2022-05\n"
            "- 최근 정비: 5주 전 정기 점검 (이상 없음)\n"
            "- 관련 부품: 팬 F-201, 열교환기 HE-105\n"
            "- 특이 사항: 없음"
        )

    return "관련 정보 없음. 검색어를 다르게 시도해주세요."


# ============================================================
# 도구 3: 불량 유형 분포 조회
# ============================================================
@tool
def check_defect_type(line: str) -> str:
    """특정 라인의 최근 불량 유형 분포를 조회한다.

    질의 예시:
      - "라인 B"
      - "라인 A"
    """
    # 실전에서는 QMS(품질관리시스템)의 결함 분류 DB 조회로 교체

    if "B" in line:
        return (
            "라인 B 불량 유형 분포 (이번 달):\n"
            "- 표면 크랙: 68% (전월 12%, 급증)\n"
            "- 치수 불량: 20% (전월 22%)\n"
            "- 색상 불량: 12% (전월 15%)"
        )

    if "A" in line:
        return (
            "라인 A 불량 유형 분포 (이번 달):\n"
            "- 치수 불량: 45% (전월 47%)\n"
            "- 표면 흠집: 32% (전월 30%)\n"
            "- 기타: 23% (전월 23%)"
        )

    if "C" in line:
        return (
            "라인 C 불량 유형 분포 (이번 달):\n"
            "- 조립 불량: 55% (전월 53%)\n"
            "- 기능 이상: 30% (전월 32%)\n"
            "- 외관 불량: 15% (전월 15%)"
        )

    return "데이터 없음. 라인 A, B, C 중에서 지정해주세요."


# ============================================================
# 도구 목록 (에이전트에 전달할 리스트)
# ============================================================
AGENT_TOOLS = [query_mes_data, graphrag_search, check_defect_type]
